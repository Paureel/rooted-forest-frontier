"""One-shot X0 exact instrument, deliberately independent of existing rMAF code.

No proposed algorithm imports this file. Leaf partitions are generated by
minimum-containing subsets; equality uses induced cluster families, and spans
are explicit undirected pair paths. Inputs: nested binary lists, integer leaves,
or None for the empty boundary. Ordinary unaugmented rooted convention.
"""
from itertools import combinations


class Tree:
    def __init__(self, raw):
        self.raw = raw
        self.child = {}
        self.parent = {}
        self.leaf = {}
        self.below = {}
        self.edges = []
        def visit(x, v):
            if isinstance(x, int) and not isinstance(x, bool):
                if x in self.leaf:
                    raise ValueError('duplicate tree label')
                self.leaf[x] = v
                self.child[v] = []
                self.below[v] = frozenset([x])
            elif isinstance(x, (list, tuple)) and len(x) == 2:
                self.child[v] = [v + '0', v + '1']
                for y, w in zip(x, self.child[v]):
                    self.parent[w] = v
                    self.edges.append((v, w))
                    visit(y, w)
                self.below[v] = self.below[v+'0'] | self.below[v+'1']
            else:
                raise ValueError('tree must be a leaf or binary pair')
        if raw is not None:
            visit(raw, '')
        self.labels = frozenset(self.leaf)

    def path(self, a, b):
        va, vb = self.leaf[a], self.leaf[b]
        ancestors = []
        while True:
            ancestors.append(va)
            if va == '':
                break
            va = self.parent[va]
        tail = []
        while vb not in ancestors:
            tail.append(vb)
            vb = self.parent[vb]
        return ancestors[:ancestors.index(vb)+1] + list(reversed(tail))

    def span(self, block):
        block = sorted(block)
        if not block:
            return frozenset()
        used = {self.leaf[block[0]]}
        for b in block[1:]:
            used.update(self.path(block[0], b))
        return frozenset(used)

    def clusters(self, block):
        s = frozenset(block)
        if not s <= self.labels:
            raise ValueError('restriction labels missing from tree')
        return frozenset(d & s for d in self.below.values() if len(d & s) >= 2)

    def restriction(self, block):
        s = frozenset(block)
        if not s:
            return None
        family = set(self.clusters(s)) | {frozenset([x]) for x in s}
        def build(c):
            if len(c) == 1:
                return next(iter(c))
            proper = [d for d in family if d < c]
            sons = [d for d in proper if not any(d < e < c for e in proper)]
            if len(sons) != 2:
                raise AssertionError('induced cluster family is not binary')
            sons.sort(key=lambda d: min(d))
            return [build(d) for d in sons]
        return build(s)

    def cherries(self):
        return sorted([sorted(d) for d in self.below.values() if len(d) == 2])

    def pendant(self, a, b):
        path = set(self.path(a,b))
        edges = [(u,v) for u,v in self.edges if u in path and v not in path]
        return [{'edge':[u,v], 'labels':sorted(self.below[v])} for u,v in edges]

    def cut_blocks(self, edges):
        cuts = {tuple(e) for e in edges}
        if not cuts <= set(self.edges):
            raise ValueError('nonexistent cut edge')
        graph = {v:set() for v in self.child}
        for u,v in self.edges:
            if (u,v) not in cuts:
                graph[u].add(v)
                graph[v].add(u)
        remaining = set(graph)
        blocks = []
        empty_regions = []
        by_vertex = {v:k for k,v in self.leaf.items()}
        while remaining:
            seed = min(remaining)
            region = {seed}
            todo = [seed]
            while todo:
                u = todo.pop()
                for v in graph[u] - region:
                    region.add(v)
                    todo.append(v)
            remaining -= region
            labels = sorted(by_vertex[v] for v in region if v in by_vertex)
            if labels:
                blocks.append(labels)
            else:
                empty_regions.append(sorted(region))
        blocks.sort(key=lambda b:min(b))
        return blocks, empty_regions


def partitions(labels):
    """Enumerate each set partition once by its block containing the minimum."""
    labels = tuple(sorted(labels))
    if not labels:
        yield []
        return
    first, rest = labels[0], labels[1:]
    for k in range(len(rest)+1):
        for chosen in combinations(rest,k):
            block = [first,*chosen]
            other = [x for x in rest if x not in chosen]
            for suffix in partitions(other):
                yield [block,*suffix]


def validate_partition(a, b, blocks, refinement=None):
    if a.labels != b.labels:
        return {'valid':False, 'reason':'tree label mismatch'}
    flat = [x for block in blocks for x in block]
    if any(not block for block in blocks):
        return {'valid':False, 'reason':'empty component'}
    if len(flat) != len(set(flat)):
        return {'valid':False, 'reason':'duplicate forest label'}
    if set(flat) != set(a.labels):
        return {'valid':False, 'reason':'missing/foreign forest label'}
    if refinement is not None and any(not any(set(c) <= set(r) for r in refinement) for c in blocks):
        return {'valid':False, 'reason':'not a refinement'}
    witness = []
    occupied_a, occupied_b = set(),set()
    for c in blocks:
        ca,cb = a.clusters(c),b.clusters(c)
        if ca != cb:
            return {'valid':False, 'reason':'wrong rooted topology', 'block':c,
                    'a_clusters':[sorted(d) for d in sorted(ca,key=lambda d:(len(d),sorted(d)))],
                    'b_clusters':[sorted(d) for d in sorted(cb,key=lambda d:(len(d),sorted(d)))]}
        sa,sb = a.span(c),b.span(c)
        if occupied_a & sa or occupied_b & sb:
            return {'valid':False, 'reason':'vertex overlap', 'block':c,
                    'a_overlap':sorted(occupied_a & sa), 'b_overlap':sorted(occupied_b & sb)}
        occupied_a.update(sa)
        occupied_b.update(sb)
        witness.append({'block':list(c),'restricted_tree':a.restriction(c),
                        'span_T':sorted(sa),'span_Tprime':sorted(sb)})
    return {'valid':True,'components':len(blocks),'witnesses':witness}


def exact(a,b,refinement=None,retain_together=None):
    if a.labels != b.labels:
        raise ValueError('tree label mismatch')
    best = len(a.labels)+1
    optima = []
    tested = 0
    for p in partitions(a.labels):
        tested += 1
        if len(p) > best:
            continue
        if retain_together is not None and not any(set(retain_together) <= set(c) for c in p):
            continue
        v = validate_partition(a,b,p,refinement)
        if v['valid']:
            if len(p) < best:
                best = len(p)
                optima = []
            optima.append(p)
    if not optima:
        raise ValueError('no valid agreement partition')
    return {'components':best,'partitions_tested':tested,'optimal_partitions':optima,
            'span_witnesses':[validate_partition(a,b,p,refinement) for p in optima]}


def applicability(a,b):
    """Source tests for Figure16 steps2a-d, on a tidied tree-tree state."""
    common = sorted([c for c in a.cherries() if c in b.cherries()])
    rows = []
    for x,y in a.cherries():
        pendant = b.pendant(x,y)
        t = len(pendant)
        rule4 = False
        for side in pendant:
            if len(side['labels']) == 1:
                z = side['labels'][0]
                rule4 |= sorted([x,z]) in b.cherries() or sorted([y,z]) in b.cherries()
        rule4 = t == 2 and rule4
        blocks = [p['labels'] for p in pendant]
        path_component = sorted(a.labels - set(x for c in blocks for x in c))
        allblocks = [*blocks,path_component]
        spans = [a.span(c) for c in allblocks]
        disjoint = all(not spans[i]&spans[j] for i in range(len(spans)) for j in range(i))
        homeomorphic = [a.clusters(c) == b.clusters(c) for c in allblocks]
        rule5 = t == 2 and disjoint and sum(homeomorphic) >= 2
        rows.append({'cherry':[x,y],'t':t,'pendants':pendant,'step2a':t==1,
                     'step2b':t>=3,'step2c':rule4,'step2d':rule5,
                     'two_cut_blocks':allblocks,'blocks_disjoint_T':disjoint,
                     'blocks_homeomorphic':homeomorphic})
    return {'common_cherries':common,'rows':rows,
            'excluded_2a_to_2d':not common and bool(rows) and
                all(not any(r[k] for k in ['step2a','step2b','step2c','step2d']) for r in rows)}


def tidy(raw_tree, raw_forest):
    """Deterministic singleton deletion and common-cherry contraction, with log."""
    tree = Tree(raw_tree)
    forest = [Tree(x) for x in raw_forest]
    expansion = {x:[x] for x in tree.labels}
    closed = []
    actions = []
    while True:
        single = sorted(x for f in forest if len(f.labels)==1 for x in f.labels)
        if single:
            x = single[0]
            closed.append(expansion.pop(x))
            tree = Tree(tree.restriction(tree.labels - {x}))
            forest = [f for f in forest if f.labels != {x}]
            actions.append({'kind':'delete_singleton','label':x,'closed_block':closed[-1]})
            continue
        common = sorted(c for c in tree.cherries() if any(c in f.cherries() for f in forest))
        if common:
            x,y = common[0]
            expansion[x] = sorted(expansion[x]+expansion.pop(y))
            tree = Tree(tree.restriction(tree.labels - {y}))
            forest = [Tree(f.restriction(f.labels-{y})) if y in f.labels else f for f in forest]
            actions.append({'kind':'contract_common_cherry','pair':[x,y],
                            'retained':x,'expanded_labels':expansion[x]})
            continue
        break
    return {'T':tree.raw,'forest_trees':[f.raw for f in forest],
            'forest_blocks':[sorted(f.labels) for f in forest],
            'expansion':expansion,'closed_components':closed,'actions':actions}


def forest_to_reference(tree, forest):
    """For an exact refinement query keep the full current forest topology.

    Blocks never mix forest components; reference tree may connect them in any
    binary fashion, since its cross-component clusters never enter a block.
    """
    if not forest:
        return Tree(None)
    raw = forest[0]
    for nxt in forest[1:]:
        raw = [raw,nxt]
    return Tree(raw)

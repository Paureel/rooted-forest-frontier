"""One-shot declaration-list audit generator for this source-core candidate.
Not a general toolkit instrument. Scans explicit public declarations, requires
closed namespaces, and emits complete #print axioms commands for each one.
"""
from pathlib import Path
import re
HERE = Path(__file__).resolve().parent
MODULES = ('CoreGraph', 'CherryCoarsening', 'CoreProgram', 'CoreInvariants')
names = []
for module in MODULES:
    stack = []
    for line in (HERE / (module + '.lean')).read_text().splitlines():
        if m := re.match(r'^namespace ([\w.]+)$', line):
            stack.append(m[1])
        elif m := re.match(r'^end ([\w.]+)$', line):
            assert stack and stack.pop() == m[1], (module, line)
        elif m := re.match(r'^(?:def|theorem|structure|inductive) ([\w.]+)', line):
            assert stack, (module, line)
            names.append('.'.join(stack + [m[1]]))
    assert not stack, (module, stack)
assert len(names) == len(set(names)) and len(names) >= 90, len(names)
text = 'import CoreInvariants\nimport CherryCoarsening\n\n'
text += '/- Complete explicit-declaration axiom audit, generated by make_audit.py. -/\n'
text += '\n'.join('#print axioms ' + n for n in names) + '\n'
(HERE / 'Audit.lean').write_text(text)
print(f'generated {len(names)} explicit declaration audits')
